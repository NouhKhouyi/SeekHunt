const DICTS: Record<Lang, Record<string, Entry>> = { es, en };
const STORAGE_KEY = "seekhunt:lang";

function detect(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "es" || saved === "en") return saved;
  } catch {
    // ignore
  }
  return navigator.language?.toLowerCase().startsWith("es") ? "es" : "en";
}

let lang: Lang = detect();
const listeners = new Set<() => void>();
document.documentElement.lang = lang;

export function setLang(next: Lang) {
  lang = next;
  document.documentElement.lang = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // Private mode: the choice lasts for this tab.
  }
  listeners.forEach((l) => l());
}

export const getLang = () => lang;
export const locale = () => (lang === "es" ? "es-ES" : "en-GB");

/** Translate a key. Unknown keys (e.g. from a newer server) fall back to Spanish, then to the key itself. */
export function translate(key: string, params: Params = {}, l: Lang = lang): string {
  const entry = DICTS[l][key] ?? DICTS.es[key];
  if (entry === undefined) return key;
  if (typeof entry === "function") return entry(params);
  return entry.replace(/\{(\w+)\}/g, (_, k: string) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

/** Server messages; rooms saved before i18n may still hold plain Spanish strings. */
export const translateMsg = (m: Msg | string | null | undefined, l: Lang = lang) => (m == null ? "" : typeof m === "string" ? m : translate(m.key, m.params, l));

const subscribe = (cb: () => void) => {
  listeners.add(cb);
  return () => listeners.delete(cb);
};

/** Re-renders the component when the language changes. */
export function useT() {
  const current = useSyncExternalStore(subscribe, getLang);
  const t = (key: Key, params?: Params) => translate(key, params, current);
  return Object.assign(t, { lang: current, msg: (m: Msg | string | null | undefined) => translateMsg(m, current) });
}
